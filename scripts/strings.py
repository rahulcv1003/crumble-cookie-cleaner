def to_message(text):
    nums = sorted(set(int(n) for n in re.findall(r"\$(\d)", text)))
    msg = re.sub(r"\$(\d)", lambda m: f"$P{m.group(1)}$", text)
    return msg, {f"p{n}": {"content": f"${n}"} for n in nums}

path = sys.argv[1]
data = json.load(open(path))
for key, (text, desc) in S.items():
    msg, ph = to_message(text)
    entry = {"message": msg, "description": desc}
    if ph: entry["placeholders"] = ph
    data[key] = entry
json.dump(data, open(path, "w"), indent=2, ensure_ascii=False)
open(path, "a").write("\n")
print(len(data), "messages")
